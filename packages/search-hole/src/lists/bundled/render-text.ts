/**
 * Renders a first-party list as the CC0 text file published in `lists/<id>.txt` (ADR-0016:
 * every list file starts with `! License: CC0-1.0`). Pure; scripts/export-lists.mjs writes the
 * files and test/lists-data checks they are in sync.
 *
 * Format, for reuse by other tools:
 * - `!` lines are comments (ABP/AdGuard). uBlacklist's "domains" subscriptions and Pi-hole skip
 *   them as invalid lines.
 * - A host entry is a plain domain line (`example.com`: the domain and its subdomains), which
 *   uBlacklist (subscription type "domains"), AdGuard Home, Pi-hole and search-hole's `domains`
 *   format read directly.
 * - A host + path entry is a uBlacklist match pattern (`*://*.example.com/answers/*`). Plain
 *   domain readers skip it, which errs on the side of not blocking the whole host.
 *
 * Output is deterministic (no dates), so the sync test can compare bytes.
 */
import type { EvidencedEntry } from './evidence.ts'
import type { FirstPartyList } from './first-party.ts'

export const LISTS_HOMEPAGE = 'https://github.com/baselissmail/search-hole/tree/main/lists'
const REPO_BLOB = 'https://github.com/baselissmail/search-hole/blob/main'

/** Repo-relative path of a list's exported text copy. */
export function exportPath(id: string): string {
  return `lists/${id}.txt`
}

/** One entry as a line: a plain domain, or a uBlacklist match pattern for host + path. */
export function exportLine(match: string): string {
  const exact = match.startsWith('=')
  const body = exact ? match.slice(1) : match
  const slash = body.indexOf('/')
  if (slash < 0) return exact ? `*://${body}/*` : body
  const host = body.slice(0, slash)
  const path = body.slice(slash)
  return `*://${exact ? '' : '*.'}${host}${path.endsWith('/') ? path : `${path}/`}*`
}

function evidenceComment(e: EvidencedEntry): string {
  const parts = [`evidence ${e.evidence}`]
  if (e.original !== undefined) parts.push(`original ${e.original}`)
  if (e.note !== undefined) parts.push(e.note)
  return `! ${parts.join(' | ')}`
}

export function renderListText(list: FirstPartyList): string {
  const lines = [
    '! License: CC0-1.0',
    `! Title: ${list.title}`,
    `! Description: ${list.description}`,
    `! Homepage: ${LISTS_HOMEPAGE}`,
    '! Expires: 7 days',
    `! search-hole kind: ${list.kind} (default mode: ${list.mode})`,
    `! Entries: ${list.entries.length}`,
    `! Source and per-entry evidence: ${REPO_BLOB}/${list.source}`,
    '! Generated by scripts/export-lists.mjs; do not edit by hand. Contributions: CC0-1.0, with evidence.',
    '!',
  ]
  for (const entry of list.entries) {
    if (typeof entry === 'string') {
      lines.push(exportLine(entry))
    } else {
      lines.push(evidenceComment(entry), exportLine(entry.match))
    }
  }
  return `${lines.join('\n')}\n`
}
